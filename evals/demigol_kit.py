def parse_name(name):
    parts = name.split("_")
    if len(parts) != 4 or parts[0] != "kit":
        return None
    return parts[1], parts[2], parts[3]


# ------------------------------------------------------------- maya bridge
def ok(resp, what):
    if resp.get("status") != "ok":
        print("FAILED %s: %s" % (what, json.dumps(resp.get("error", resp))[:500]))
        sys.exit(1)
    return resp["result"]


def run(code, what, timeout=2400.0):
    out = ok(call("execute_python", {"code": code}, timeout), what)
    if out.get("traceback"):
        print("PYTHON FAILED (%s):\n%s" % (what, out["traceback"][:2000]))
        sys.exit(1)
    return out


