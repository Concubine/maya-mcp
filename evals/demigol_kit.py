"""Demigol KIT OF PARTS - one-cell pieces that dress the whole city.

Not buildings. Pieces. The generator already decides, per cell, what material
sits where and which faces are exposed; this kit is the vocabulary it draws
with, so dressing 50 buildings costs the same as dressing one and newly
generated buildings are dressed for free.

THE CONSTRAINT THAT DECIDES EVERYTHING is the budget, and it is the exact
inverse of the hero buildings. A hero chunk is drawn once and could afford
detail; a kit piece is instanced across ~46,000 standing cells. So:

  * every piece is built from AXIS-ALIGNED BOXES, 12 triangles each. That makes
    the budget arithmetic exact rather than estimated - a 6-box piece is 72
    triangles, and the check is a count, not a measurement to be argued with.
  * ONE SHARED MATERIAL for the whole kit. Material identity comes from a
    single 512px atlas: each box is UV-packed into one 128px patch, so brick,
    glass, steel, a dark recess and the warning amber all coexist under one
    shader. An engine batches instanced geometry by material, and a kit with
    eight materials cannot be drawn at city scale.

Geometry is inset 5 mm inside the 3 m cell, which is the z-fighting fix:
adjacent cells would otherwise share exact coplanar faces. Collision is
generated by the game from the grid and never from this art, so the inset is
free.

Every piece is authored FACING +Z. The shell rotates in 90 deg steps to face
whichever way a cell is exposed, so a facade piece is authored once, not four
times. Corners are the one exception and are authored reading from +Z and +X.

Run:  set MAYA_MCP_PORT=9878 && .venv/Scripts/python.exe evals/demigol_kit.py
Package: evals/demigol_kit/
"""

