    names = list(pieces)

    # Budget is arithmetic, checked BEFORE anything is built: a piece that
    # cannot fit is a design error, not a render to look at.
    over = []
    for name, boxes in pieces.items():
        parsed = parse_name(name)
        if not parsed:
            print("NAME DOES NOT PARSE: %s" % name)
            sys.exit(1)
        role, context, variant = parsed
        budget = TRI_BUDGET.get(context, TRI_BUDGET.get(role, TRI_BUDGET_DEFAULT))
        tris = len(boxes) * TRIS_PER_BOX
        if tris > budget:
            over.append((name, tris, budget))
        for b in boxes:
            if b["patch"] not in PATCH:
                print("UNKNOWN PATCH %r on %s" % (b["patch"], name))
                sys.exit(1)
            for i in range(3):
                half = b["dim"][i] / 2.0
                reach = abs(b["pos"][i]) + half
                # The limit is now the CELL face plus the outset allowance,
                # not the inset envelope. Past 0.5 m an overhang would reach
                # into the core of the next cell and clip badly when that
                # neighbour is torn away, which is the reason for the cap.
                if reach > OUT + 1e-6:
                    print("BOX EXCEEDS THE OUTSET ALLOWANCE on %s: axis %d, "
                          "%.4f m from centre (limit %.3f)"
                          % (name, i, reach, OUT))
