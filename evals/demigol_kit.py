# A wall built out of the kit, on the real 3 m lattice, with pieces rotated by
# the same 90 degree steps the shell uses. This is the only honest evidence for
# the contract's tiling clause: the inset guarantees pieces cannot intersect,
# but it does not by itself prove they MEET - that a glass panel beside a brick
# panel beside a steel column reads as one wall rather than as three objects
# with gaps between them.
TILING_CODE = r'''
import json
import maya.cmds as cmds
plan = json.loads(PLAN)
made = []
for item in plan:
    src = "|" + item["piece"]
    dup = cmds.duplicate(src, name="wall_%d_%d" % (item["x"], item["y"]),
                         returnRootsOnly=True)[0]
    dup = (cmds.ls(dup, long=True) or [dup])[0]
    if item.get("ry"):
        cmds.rotate(0, item["ry"], 0, dup, absolute=True)
    cmds.move(item["x"] * 3.0, item["y"] * 3.0, 0, dup, absolute=True)
    made.append(dup)
grp = cmds.group(made, name="kit_wall")
grp = (cmds.ls(grp, long=True) or [grp])[0]
bb = cmds.exactWorldBoundingBox(grp)
result = {"group": grp, "pieces": len(made),
          "bbox": [round(q, 4) for q in bb]}
result
'''


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    atlas_path = os.path.join(OUT_DIR, "kit_atlas.png").replace("\\", "/")
    build_atlas(atlas_path)
    print("atlas %s" % atlas_path)

    pieces = PIECES()
    names = list(pieces)

    # Budget is arithmetic, checked BEFORE anything is built: a piece that
    # cannot fit is a design error, not a render to look at.
    over = []
    for name, boxes in pieces.items():
        parsed = parse_name(name)
        if not parsed:
            print("NAME DOES NOT PARSE: %s" % name)
            sys.exit(1)
        role, context, variant = parsed
        budget = TRI_BUDGET.get(context, TRI_BUDGET.get(role, TRI_BUDGET_DEFAULT))
        tris = len(boxes) * TRIS_PER_BOX
        if tris > budget:
            over.append((name, tris, budget))
        for b in boxes:
            if b["patch"] not in PATCH:
                print("UNKNOWN PATCH %r on %s" % (b["patch"], name))
                sys.exit(1)
            for i in range(3):
                half = b["dim"][i] / 2.0
                if abs(b["pos"][i]) + half > H + 1e-6:
                    print("BOX ESCAPES THE CELL on %s: axis %d, %.4f"
                          % (name, i, abs(b["pos"][i]) + half))
                    sys.exit(1)
    if over:
        for name, tris, budget in over:
            print("OVER BUDGET %-26s %d tris > %d" % (name, tris, budget))
        sys.exit(1)

    spec = {
        "atlas": atlas_path, "cols": ATLAS_COLS, "rows": ATLAS_ROWS,
        "margin": 0.03,
        "pieces": [
            {"name": n,
             "boxes": [dict(b, patch=PATCH[b["patch"]][0]) for b in pieces[n]]}
            for n in names
        ],
    }

    ok(call("new_scene", {"confirm": True}, 300.0), "new_scene")
    built = ast.literal_eval(
        run("SPEC = %r\n%s" % (json.dumps(spec), BUILD_CODE), "build")["result_repr"])
    print("built %d pieces" % built["pieces"])

    check = ast.literal_eval(
        run("NAMES = %r\n%s" % (names, CHECK_CODE), "check")["result_repr"])

    fbx = os.path.join(OUT_DIR, "demigol_kit.fbx").replace("\\", "/")
    run("NAMES = %r\nFBX = %r\n%s" % (names, fbx, EXPORT_CODE), "export")

    # Contact sheet, one piece per tile. A single wide shot of the kit laid
    # out was tried first and is the wrong instrument: from one camera the
    # pieces are seen mostly from above, which is the one direction none of
    # this relief faces. Each piece gets its own framed render instead, and
    # every tile is checked for a subject - a "valid PNG of nothing" is the
    # failure mode a render gate exists to catch.
    ok(call("setup_lighting", {"preset": "three_point", "intensity": 3.2,
                               "replace_existing": True}, 180.0), "lighting")
    tiles, blanks = [], []
    for name in names:
        shot = ok(call("render_scene", {
            "angles": ["three_quarter"], "renderer": "arnold", "resolution": 320,
            "samples": 2, "zoom": 1.0,
            "isolate": ["|" + name], "target": ["|" + name]}, 900.0),
            "render %s" % name)["images"][0]
        png = base64.b64decode(shot["png_b64"])
        if images.pixel_stats(png)["blank"]:
            blanks.append(name)
        tiles.append(png)
    sheet_png = images.contact_sheet(tiles, cols=7)
    with open(os.path.join(OUT_DIR, "contact_sheet.png"), "wb") as fh:
        fh.write(sheet_png)
    stats = images.pixel_stats(sheet_png)
    if blanks:
        print("BLANK TILES (rendered nothing): %s" % ", ".join(blanks))

    # ---- tiling proof: a wall built out of the kit on the real 3 m lattice --
    # The corner sits at the RIGHT end, where the exposed pair is (+Z, +X) -
    # the orientation corners are authored in. Worth stating because it is a
    # property of the rotation rule, not an accident: rotating (+Z,+X) by 90
    # degree steps yields (+X,-Z), (-Z,-X), (-X,+Z), which are exactly the four
    # corners of a rectangular plan walked in order. So one corner piece
    # serves all four corners of a building - but the reflex pair (+Z,-X), a
    # wall that simply ENDS, is not reachable by rotation and would need a
    # mirrored variant.
    wall = []
    for y in range(5):
        wall.append({"piece": "kit_brick_corner_a" if y % 2 else
                              "kit_brick_corner_b", "x": 5, "y": y, "ry": 0})
    for x, piece in enumerate(["kit_steel_lobby_a", "kit_glass_lobby_a",
                               "kit_glass_lobby_a", "kit_brick_lobby_a",
                               "kit_concrete_base_a"]):
        wall.append({"piece": piece, "x": x, "y": 0, "ry": 0})
    for x, piece in enumerate(["kit_steel_column_b", "kit_glass_facade_a",
                               "kit_glass_facade_b", "kit_infill_facade_a",
                               "kit_brick_facade_a"]):
        wall.append({"piece": piece, "x": x, "y": 1, "ry": 0})
    for x, piece in enumerate(["kit_steel_column_a", "kit_infill_facade_b",
                               "kit_glass_facade_c", "kit_infill_facade_c",
                               "kit_brick_facade_b"]):
        wall.append({"piece": piece, "x": x, "y": 2, "ry": 0})
    for x in range(5):
        wall.append({"piece": "kit_concrete_beam_a", "x": x, "y": 3, "ry": 0})
    for x in range(5):
        wall.append({"piece": "kit_concrete_roof_b", "x": x, "y": 4, "ry": 0})

    tiling = ast.literal_eval(
        run("PLAN = %r\n%s" % (json.dumps(wall), TILING_CODE), "tiling")["result_repr"])
    wall_shots = ok(call("render_scene", {
        "angles": ["front", "three_quarter"], "renderer": "arnold",
        "resolution": 900, "samples": 3, "zoom": 0.98,
        "isolate": ["|kit_wall"], "target": ["|kit_wall"]}, 2400.0),
        "render wall")["images"]
    wall_pngs = [base64.b64decode(s["png_b64"]) for s in wall_shots]
    wall_sheet = images.contact_sheet(wall_pngs, cols=2)
    with open(os.path.join(OUT_DIR, "tiling_proof.png"), "wb") as fh:
        fh.write(wall_sheet)
    wall_blank = [i for i, p in enumerate(wall_pngs) if images.pixel_stats(p)["blank"]]

    # 6 cells wide x 5 tall on a 3 m lattice, measured against what the wall
    # SHOULD span if every piece sat in its own cell and none escaped.
    want = [-1.5, -1.5, -1.5, 6 * 3.0 - 1.5, 5 * 3.0 - 1.5, 1.5]
    wall_ok = all(abs(tiling["bbox"][i] - want[i]) <= INSET + 1e-3
                  for i in range(6))
    print("\ntiling proof: %d pieces, bbox %s"
          % (tiling["pieces"], tiling["bbox"]))
    print("  expected    %s -> %s"
          % ([round(q, 4) for q in want], "MATCHES" if wall_ok else "MISMATCH"))

    measured = check["tris"]
    entries = []
    total_tris = 0
    for name in names:
        role, context, variant = parse_name(name)
        tris = measured.get(name, 0)
        total_tris += tris
        entries.append({
            "name": name, "role": role, "context": context, "variant": variant,
            "triangles": tris, "boxes": len(pieces[name]),
            "budget": TRI_BUDGET.get(context, TRI_BUDGET_DEFAULT),
        })

    print("\n%-26s %-9s %-8s %6s %6s" % ("piece", "role", "context", "tris", "cap"))
    for e in entries:
        flag = "" if e["triangles"] <= e["budget"] else "  OVER"
        print("%-26s %-9s %-8s %6d %6d%s"
              % (e["name"], e["role"], e["context"], e["triangles"],
                 e["budget"], flag))
    print("\n%d pieces, %d triangles total, %d shading group(s): %s"
          % (len(entries), total_tris, len(check["shading_groups"]),
             ", ".join(check["shading_groups"])))
    print("widest measured extent %.5f m (cell half-extent %.3f)"
          % (check["max_abs_extent"], H))
    print("UV range across every piece %.5f .. %.5f (atlas is 0..1)"
          % (check["uv_min"], check["uv_max"]))
    print("geometry failures: %d" % check["fail_count"])
    for name, why in check["fails"]:
        print("    %-26s %s" % (name, why))
    print("contact sheet %d tiles, %d blank, clipped %.4f, mean luma %.1f"
          % (len(tiles), len(blanks), stats["clipped_fraction"],
             stats.get("mean_luma", -1)))

    manifest = {
        "contract": "Demigol KIT OF PARTS",
        "scope": "one-cell pieces, not buildings",
        "units": "metres, Y-up, 1 unit = 1 m, cell = 3 m",
        "envelope": "3 x 3 x 3 m, render geometry inset %.3f m" % INSET,
        "pivot": "cell centre (0,0,0) on every piece",
        "authored_facing": "+Z; the shell rotates in 90 degree steps. Corner "
                           "pieces read from +Z AND +X.",
        "material": {
            "shared": True,
            "shader": "kit_material (standardSurface)",
            "atlas": "kit_atlas.png",
            "atlas_grid": [ATLAS_COLS, ATLAS_ROWS],
            "patches": {k: {"index": v[0], "rgb": list(v[1])}
                        for k, v in PATCH.items()},
            "note": "every piece samples one 128 px patch of the single atlas, "
                    "so the whole kit draws in one batch",
        },
        "budgets": {"interior": TRI_BUDGET["interior"],
                    "default": TRI_BUDGET_DEFAULT,
                    "tris_per_box": TRIS_PER_BOX},
        "totals": {"pieces": len(entries), "triangles": total_tris,
                   "shading_groups": check["shading_groups"],
                   "widest_extent_m": check["max_abs_extent"],
                   "uv_range": [check["uv_min"], check["uv_max"]]},
        "self_check": {
            "budget": "arithmetic, before the build: every piece is boxes at 12 "
                      "tris each, so the count is exact",
            "envelope": "every box checked against the inset cell before build, "
                        "then every finished piece re-measured in-scene",
            "closed": "boundary_edges == 0 and no non-manifold edges per piece",
            "uv": "every piece's UV bbox measured inside 0..1",
            "failures": check["fail_count"],
        },
        "pieces": entries,
        "tiling_proof": {
            "what": "a 6 x 5 wall built from the kit on the real 3 m lattice, "
                    "mixing brick, infill, glass, steel and a corner run",
            "pieces": tiling["pieces"],
            "measured_bbox": tiling["bbox"],
            "expected_bbox": [round(q, 4) for q in want],
            "lattice_conformant": bool(wall_ok),
            "corner_rule": "rotating the authored (+Z,+X) corner by 90 degree "
                           "steps gives (+X,-Z), (-Z,-X), (-X,+Z) - exactly the "
                           "four corners of a rectangular plan. A wall that "
                           "simply ENDS needs (+Z,-X), which is a mirror, not a "
                           "rotation, and is not in this kit.",
        },
        "files": ["demigol_kit.fbx", "kit_atlas.png", "contact_sheet.png",
                  "tiling_proof.png"],
    }
    with open(os.path.join(OUT_DIR, "manifest.json"), "w") as fh:
        json.dump(manifest, fh, indent=2)

    sys.exit(0 if check["fail_count"] == 0 and not blanks
             and not wall_blank and wall_ok else 1)


if __name__ == "__main__":
    main()
